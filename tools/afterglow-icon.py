import math
import sys
from PIL import Image, ImageDraw, PngImagePlugin

image = Image.new("RGB", (1024, 1024), "#090e12")
draw = ImageDraw.Draw(image)
for layer in range(3):
    points = []
    for segment in range(385):
        angle = segment * math.tau / 384
        radius = 210 + layer * 37 + 27 * math.sin(angle * 3)
        points.append((512 + math.cos(angle) * radius * 1.35,
                       512 + math.sin(angle) * radius * 0.8))
    draw.line(points, fill=("#eeb875", "#87cabb", "#526b65")[layer],
              width=(10, 5, 3)[layer], joint="curve")
metadata = PngImagePlugin.PngInfo()
metadata.add_text("Origin", "Original Afterglow geometric mark; generated by tools/afterglow-icon.py")
image.resize((512, 512), Image.Resampling.LANCZOS).save(sys.argv[1], pnginfo=metadata)
